-- Gamarra TV: tablas para administrar canales, radios y carrusel desde Supabase.
-- Ejecutar en Supabase > SQL Editor. No borra tablas existentes.
create table if not exists public.canales_tv (
  id bigint generated by default as identity primary key,
  nombre text not null,
  logo_url text not null,
  stream_url text not null,
  descripcion text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.radios (
  id bigint generated by default as identity primary key,
  nombre text not null,
  logo_url text not null,
  stream_url text not null,
  descripcion text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.carrusel_inicio (
  id bigint generated by default as identity primary key,
  titulo text not null,
  imagen_url text not null,
  enlace_url text,
  descripcion text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists canales_tv_activo_orden_idx on public.canales_tv (activo, orden);
create index if not exists radios_activo_orden_idx on public.radios (activo, orden);
create index if not exists carrusel_inicio_activo_orden_idx on public.carrusel_inicio (activo, orden);

-- Lectura pública del contenido activo; escritura solo para usuarios autenticados.
alter table public.canales_tv enable row level security;
alter table public.radios enable row level security;
alter table public.carrusel_inicio enable row level security;
drop policy if exists "Lectura pública canales activos" on public.canales_tv;
create policy "Lectura pública canales activos" on public.canales_tv for select to anon, authenticated using (activo = true or auth.uid() is not null);
drop policy if exists "Admins gestionan canales" on public.canales_tv;
create policy "Admins gestionan canales" on public.canales_tv for all to authenticated using (true) with check (true);
drop policy if exists "Lectura pública radios activas" on public.radios;
create policy "Lectura pública radios activas" on public.radios for select to anon, authenticated using (activo = true or auth.uid() is not null);
drop policy if exists "Admins gestionan radios" on public.radios;
create policy "Admins gestionan radios" on public.radios for all to authenticated using (true) with check (true);
drop policy if exists "Lectura pública carrusel activo" on public.carrusel_inicio;
create policy "Lectura pública carrusel activo" on public.carrusel_inicio for select to anon, authenticated using (activo = true or auth.uid() is not null);
drop policy if exists "Admins gestionan carrusel" on public.carrusel_inicio;
create policy "Admins gestionan carrusel" on public.carrusel_inicio for all to authenticated using (true) with check (true);

