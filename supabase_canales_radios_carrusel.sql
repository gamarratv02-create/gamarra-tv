-- Ejecutar una sola vez en Supabase > SQL Editor > New query.
-- Crea las tablas que usa el panel administrativo de Gamarra TV.

create table if not exists public.canales_tv (
  id bigint generated by default as identity primary key,
  nombre text not null,
  logo_url text not null,
  stream_url text not null,
  orden integer not null default 1,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.emisoras_radio (
  id bigint generated by default as identity primary key,
  nombre text not null,
  logo_url text not null,
  stream_url text not null,
  orden integer not null default 1,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.carrusel_inicio (
  id bigint generated by default as identity primary key,
  titulo text not null,
  imagen_url text not null,
  enlace_url text,
  orden integer not null default 1,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.canales_tv enable row level security;
alter table public.emisoras_radio enable row level security;
alter table public.carrusel_inicio enable row level security;

-- Lectura pública solo de los elementos activos.
drop policy if exists "Lectura publica canales activos" on public.canales_tv;
create policy "Lectura publica canales activos" on public.canales_tv
for select to anon, authenticated using (activo = true);
drop policy if exists "Lectura publica emisoras activas" on public.emisoras_radio;
create policy "Lectura publica emisoras activas" on public.emisoras_radio
for select to anon, authenticated using (activo = true);
drop policy if exists "Lectura publica carrusel activo" on public.carrusel_inicio;
create policy "Lectura publica carrusel activo" on public.carrusel_inicio
for select to anon, authenticated using (activo = true);

-- El panel requiere sesión iniciada para insertar, editar y eliminar.
drop policy if exists "Administrar canales con sesion" on public.canales_tv;
create policy "Administrar canales con sesion" on public.canales_tv
for all to authenticated using (true) with check (true);
drop policy if exists "Administrar emisoras con sesion" on public.emisoras_radio;
create policy "Administrar emisoras con sesion" on public.emisoras_radio
for all to authenticated using (true) with check (true);
drop policy if exists "Administrar carrusel con sesion" on public.carrusel_inicio;
create policy "Administrar carrusel con sesion" on public.carrusel_inicio
for all to authenticated using (true) with check (true);

create index if not exists canales_tv_orden_idx on public.canales_tv (orden, created_at);
create index if not exists emisoras_radio_orden_idx on public.emisoras_radio (orden, created_at);
create index if not exists carrusel_inicio_orden_idx on public.carrusel_inicio (orden, created_at);
